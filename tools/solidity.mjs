// SPDX-License-Identifier: MIT
// @efs/solidity re-exports the contracts' Solidity consumer closure, byte for byte, from the vendored snapshot
// (protocol-inputs/contracts, see tools/inputs.mjs): src/interfaces/ outside internal/, and the compile-in
// libraries Keys, EfsNative and EfsFiles. Files keep their relative paths, so their relative imports still resolve.
// It also generates the Keys golden vectors as Solidity constants for the package's own tests.
//   node tools/solidity.mjs           write
//   node tools/solidity.mjs --check   fail if anything differs from the snapshot
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { getAddress } from "viem";
import { fail, ok, ROOT } from "./lib/util.mjs";

const IN = join(ROOT, "protocol-inputs/contracts");
const PKG = join(ROOT, "packages/solidity");
const check = process.argv.includes("--check");
const lock = JSON.parse(readFileSync(join(ROOT, "protocol-inputs/lock.json"), "utf8"));
const sha = (b) => createHash("sha256").update(b).digest("hex");

/** The closure: package path → snapshot path. */
const closure = {};
for (const f of readdirSync(join(IN, "src/interfaces")).sort())
  if (f.endsWith(".sol")) closure[`interfaces/${f}`] = `src/interfaces/${f}`;
for (const f of ["Keys.sol", "EfsNative.sol", "EfsFiles.sol"]) closure[`lib/${f}`] = `src/lib/${f}`;

const out = {};
for (const [to, from] of Object.entries(closure)) out[`src/${to}`] = readFileSync(join(IN, from));
out["src/PROVENANCE.json"] = Buffer.from(
  `${JSON.stringify(
    {
      schema: "efs-solidity-provenance/1",
      note: "Copied byte for byte from efs-project/contracts-v2 at `commit` by tools/solidity.mjs. Do not edit.",
      contracts: { repo: lock.contracts.repo, commit: lock.contracts.commit },
      files: Object.fromEntries(Object.keys(closure).map((p) => [p, sha(out[`src/${p}`])])),
    },
    null,
    2,
  )}\n`,
);

// Golden vectors for test/Keys.t.sol, as constants (no file-system cheatcodes needed).
{
  const v = JSON.parse(readFileSync(join(IN, "test/vectors/ids.json"), "utf8"));
  const lit = (x) =>
    typeof x === "number"
      ? String(x)
      : /^0x[0-9a-fA-F]{40}$/.test(x)
        ? getAddress(x)
        : /^0x[0-9a-fA-F]{64}$/.test(x)
          ? x.toLowerCase()
          : null;
  const kind = (x) =>
    typeof x === "number" ? "uint256" : /^0x[0-9a-fA-F]{40}$/.test(x) ? "address" : "bytes32";
  let src = `// SPDX-License-Identifier: MIT
// GENERATED by tools/solidity.mjs from contracts test/vectors/ids.json (${lock.contracts.commit.slice(0, 12)}). DO NOT EDIT.
pragma solidity ^0.8.27;

library KeyVectors {
`;
  // forge fmt's layout (line_length 100): a declaration that does not fit breaks after `=`, value indented.
  const constant = (decl, value) => {
    const one = `    ${decl} = ${value};`;
    return one.length <= 100 ? `${one}\n` : `    ${decl} =\n        ${value};\n`;
  };
  const emit = (prefix, obj) => {
    for (const [k, x] of Object.entries(obj)) {
      const l = typeof x === "number" || typeof x === "string" ? lit(x) : null;
      if (l === null) continue; // arrays and byte strings are written out by hand in the test
      src += constant(`${kind(x)} internal constant ${prefix}_${k}`, l);
    }
  };
  emit("IN", v.inputs);
  emit("OUT", v.outputs);
  src += constant("bytes internal constant IN_body", `hex"${v.inputs.body.slice(2)}"`);
  src += constant("bytes32 internal constant IN_refType0", v.inputs.refTypes[0].toLowerCase());
  src += constant("bytes32 internal constant IN_refType1", v.inputs.refTypes[1].toLowerCase());
  src += "}\n";
  out["test/generated/KeyVectors.sol"] = Buffer.from(src);
}

let drift = 0;
if (!check) {
  for (const d of ["src/interfaces", "src/lib", "test/generated"])
    rmSync(join(PKG, d), { recursive: true, force: true });
}
for (const [rel, bytes] of Object.entries(out)) {
  const path = join(PKG, rel);
  if (check) {
    if (!existsSync(path) || !readFileSync(path).equals(bytes)) {
      fail(`packages/solidity/${rel} differs from the snapshot (run pnpm generate)`);
      drift++;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, bytes);
  }
}
if (check) {
  // Nothing extra in the generated directories either.
  for (const d of ["src/interfaces", "src/lib"]) {
    for (const f of existsSync(join(PKG, d)) ? readdirSync(join(PKG, d)) : [])
      if (!(`${d}/${f}` in out)) {
        fail(`packages/solidity/${d}/${f} is not part of the closure`);
        drift++;
      }
  }
}
if (!drift)
  ok(
    `${check ? "checked" : "wrote"} the Solidity closure: ${Object.keys(closure).length} files from contracts ${lock.contracts.commit.slice(0, 12)}`,
  );
