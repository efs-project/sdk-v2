// The export index of @efs/sdk: every name each public entry point exports (packages/sdk/package.json `exports`),
// its kind, and the first sentence of its JSDoc, rendered into docs/design/api-0.1.md between the
// `export-index` markers. The SDK's barrels list every export explicitly (no `export *`), so the index is read from
// the source text; each name is followed through its re-exports to the declaration that documents it.
//
//   node tools/api-index.mjs write    regenerate the block in api-0.1.md
//   node tools/api-index.mjs check    exit 1 if the block is stale (packages/sdk/test/docs-api.test.ts runs it too)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PKG = join(ROOT, "packages/sdk");
export const API_DOC = join(ROOT, "docs/design/api-0.1.md");
const START =
  "<!-- export-index:start (generated by node tools/api-index.mjs write; do not edit) -->";
const END = "<!-- export-index:end -->";

/** The public entry points: import specifier → source file. JSON and fixture subpaths have no code. */
export function entryPoints() {
  const pkg = JSON.parse(readFileSync(join(PKG, "package.json"), "utf8"));
  const out = {};
  for (const [k, v] of Object.entries(pkg.exports)) {
    const t = typeof v === "string" ? v : (v.node?.default ?? v.import ?? v.default);
    if (typeof t !== "string" || !t.startsWith("./dist/") || !t.endsWith(".js")) continue;
    out[k === "." ? "@efs/sdk" : `@efs/sdk/${k.slice(2)}`] = join(
      PKG,
      "src",
      t.slice("./dist/".length).replace(/\.js$/, ".ts"),
    );
  }
  return out;
}

const source = (file) =>
  readFileSync(existsSync(file) ? file : join(file.replace(/\.ts$/, ""), "index.ts"), "utf8");
const regexName = (name) => name.replace(/\$/g, "\\$");
const declaration = (name) =>
  new RegExp(
    `(?:(/\\*\\*(?:(?!\\*/)[\\s\\S])*\\*/)\\s*)?export\\s+(?:declare\\s+)?(?:async\\s+)?(function|const|let|class|interface|type|enum)\\s+${regexName(name)}\\b`,
  );
const RE_EXPORT = /export\s+(type\s+)?\{([^}]*)\}\s*from\s*"([^"]+)"/g;
const parts = (list) =>
  list
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((p) => {
      const typeOnly = /^type\s+/.test(p);
      const [orig, alias] = p.replace(/^type\s+/, "").split(/\s+as\s+/);
      return { orig, name: alias ?? orig, typeOnly };
    });

/** The declaration of `name` as `file` exports it, following re-exports. */
function find(file, name, depth = 0) {
  if (depth > 8) return null;
  const src = source(file);
  const m = declaration(name).exec(src);
  if (m) return { kind: m[2], doc: m[1] ?? null };
  for (const x of src.matchAll(RE_EXPORT))
    for (const p of parts(x[2]))
      if (p.name === name)
        return find(join(dirname(file), x[3].replace(/\.js$/, ".ts")), p.orig, depth + 1);
  return null;
}

/** The first sentence of a JSDoc block, on one line ("@internal" when it is marked so). */
export function summaryOf(doc) {
  if (!doc) return "";
  const text = doc
    .replace(/^\/\*\*|\*\/$/g, "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, ""))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
  if (/(^|\s)@internal\b/.test(text)) return "@internal";
  const first = text.split(/(?<=[.!?])\s+(?=[A-Z`(])/)[0] ?? "";
  return first.replace(/\s*@\w+.*$/, "").trim();
}

/** Every export of every entry point, in the barrel's order: name, kind, summary. */
export function exportIndex() {
  const out = {};
  for (const [entry, file] of Object.entries(entryPoints())) {
    const src = source(file);
    const names = [];
    for (const x of src.matchAll(RE_EXPORT)) for (const p of parts(x[2])) names.push(p.name);
    for (const m of src.matchAll(
      /^export\s+(?:declare\s+)?(?:async\s+)?(?:function|const|let|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm,
    ))
      names.push(m[1]);
    out[entry] = names.map((name) => {
      const d = find(file, name);
      if (!d)
        throw new Error(`api-index: ${entry} exports ${name}, but its declaration was not found`);
      return { name, kind: d.kind, summary: summaryOf(d.doc) };
    });
  }
  return out;
}

const VALUE = new Set(["function", "const", "let", "class", "enum"]);
export const isValue = (kind) => VALUE.has(kind);

/** The markdown block: one table per entry point, values first, then types, each alphabetical. */
export function renderIndex(index = exportIndex()) {
  const cell = (s) => s.replace(/\|/g, "\\|");
  let md = `${START}\n\n`;
  md +=
    "Every name each entry point exports, with the first sentence of its JSDoc. Functions and constants always " +
    "have one; a type without one is documented by the functions that take or return it, and field by field in " +
    "its declaration (the published `.d.ts`). `pnpm check` fails when this list is out of date.\n";
  for (const [entry, rows] of Object.entries(index)) {
    const sorted = [...rows].sort(
      (a, b) =>
        Number(isValue(b.kind)) - Number(isValue(a.kind)) || a.name.localeCompare(b.name, "en"),
    );
    md += `\n#### \`${entry}\`\n\n| Export | Kind | Summary |\n| --- | --- | --- |\n`;
    for (const r of sorted) md += `| \`${r.name}\` | ${r.kind} | ${cell(r.summary)} |\n`;
  }
  return `${md}\n${END}`;
}

/** api-0.1.md with its export-index block replaced by `block` (appended in its own section when absent). */
export function withIndex(doc, block) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a >= 0 && b > a) return doc.slice(0, a) + block + doc.slice(b + END.length);
  return `${doc.trimEnd()}\n\n## Appendix: every export\n\n${block}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const mode = process.argv[2];
  const doc = readFileSync(API_DOC, "utf8");
  const next = withIndex(doc, renderIndex());
  if (mode === "write") {
    writeFileSync(API_DOC, next);
    console.log("✓ wrote the export index into docs/design/api-0.1.md");
  } else if (mode === "check") {
    if (next !== doc) {
      console.error(
        "✗ docs/design/api-0.1.md's export index is stale: run node tools/api-index.mjs write",
      );
      process.exit(1);
    }
    console.log("✓ the export index in docs/design/api-0.1.md is current");
  } else {
    console.error("usage: node tools/api-index.mjs write|check");
    process.exit(2);
  }
}
